-- ========================================================
-- Supabase (PostgreSQL) Schema Migration for LINE AI Bot
-- Integrated with pgvector for Semantic Similarity Search
-- ========================================================

-- 1. Enable pgvector extension for Vector Search
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Create `knowledge_base` table (Primary FAQ with Vector)
CREATE TABLE IF NOT EXISTS public.knowledge_base (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category TEXT NOT NULL,
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  keywords TEXT,
  vector_array vector(384), -- 384D Vector Embeddings
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create `knowledgearticle` table (Detailed Articles with Vector)
CREATE TABLE IF NOT EXISTS public.knowledgearticle (
  id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
  source_id TEXT,
  category TEXT NOT NULL,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  keywords TEXT NOT NULL,
  vector vector(384), -- 384D Vector Embeddings
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Create `chat_messages` table (LINE & Admin Chat History)
CREATE TABLE IF NOT EXISTS public.chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender TEXT NOT NULL CHECK (sender IN ('user', 'bot', 'admin')),
  platform TEXT NOT NULL CHECK (platform IN ('web', 'line', 'admin')),
  message TEXT NOT NULL,
  line_user_id TEXT NOT NULL,
  matched_score NUMERIC(5,4),
  matched_category TEXT,
  ai_model_used TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Create `broadcast_logs` table
CREATE TABLE IF NOT EXISTS public.broadcast_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id BIGINT,
  sender_name TEXT NOT NULL,
  message TEXT NOT NULL,
  target_group TEXT NOT NULL,
  recipient_count INT DEFAULT 0,
  status TEXT DEFAULT 'success',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Create `admins` table
CREATE TABLE IF NOT EXISTS public.admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT DEFAULT 'admin' CHECK (role IN ('superadmin', 'admin', 'editor')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ========================================================
-- Vector Similarity Match Function (Cosine Similarity)
-- ========================================================
CREATE OR REPLACE FUNCTION match_knowledge(
  query_embedding vector(384),
  match_threshold float,
  match_count int
)
RETURNS TABLE (
  id bigint,
  question text,
  answer text,
  category text,
  similarity float
)
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN QUERY
  SELECT
    kb.id,
    kb.question,
    kb.answer,
    kb.category,
    1 - (kb.vector_array <=> query_embedding) AS similarity
  FROM public.knowledge_base kb
  WHERE 1 - (kb.vector_array <=> query_embedding) > match_threshold
  ORDER BY kb.vector_array <=> query_embedding
  LIMIT match_count;
END;
$$;
